/**
 * Generates src/generated/cfnext-package.ts: the REAL cfnext package
 * (manifest + readme + gzipped tarball, base64) embedded into the Worker at
 * build time so installs resolve to working code, not stubs.
 *
 * Deterministic: fixed tar mtimes, sorted file order, mtime-derived publish
 * date. Re-run after changing packages/cfnext (part of `bun run deploy`).
 *
 * Excluded from the payload: dist/bin (101MB compiled CLI artifact) and
 * *.map sourcemaps.
 */
import { createHash } from "node:crypto"
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

import { createTarGz } from "../tar"

const REGISTRY_DIR = new URL("../..", import.meta.url).pathname
const PACKAGE_DIR = join(REGISTRY_DIR, "..", "cfnext")
const REPO_ROOT = join(REGISTRY_DIR, "..", "..")
const OUT_FILE = join(REGISTRY_DIR, "src", "generated", "cfnext-package.ts")

const EXTRA_FILES = ["package.json", "README.md"]
const EXCLUDE_SEGMENTS = new Set(["node_modules"])
const EXCLUDE_PREFIXES = ["dist/bin/"]
const EXCLUDE_SUFFIXES = [".map"]

function listFiles(dir: string): string[] {
  const out: string[] = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (EXCLUDE_SEGMENTS.has(entry.name)) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...listFiles(full))
    else if (entry.isFile()) out.push(full)
  }
  return out
}

export function collectPackageFiles(): Array<{ name: string; content: string }> {
  const pkg = JSON.parse(readFileSync(join(PACKAGE_DIR, "package.json"), "utf8")) as {
    files?: string[]
    version?: string
  }
  const globs = [...(pkg.files ?? []), ...EXTRA_FILES]
  const absolute = new Set<string>()
  for (const glob of globs) {
    const target = join(PACKAGE_DIR, glob)
    if (statSync(target).isDirectory()) {
      for (const file of listFiles(target)) absolute.add(file)
    } else {
      absolute.add(target)
    }
  }
  // LICENSE lives at the repo root.
  if (statSync(join(REPO_ROOT, "LICENSE"), { throwIfNoEntry: false })) {
    absolute.add(join(REPO_ROOT, "LICENSE"))
  }

  const files = [...absolute]
    .filter((file) => {
      const rel = relative(PACKAGE_DIR, file).split(sep).join("/")
      if (EXCLUDE_PREFIXES.some((prefix) => rel.startsWith(prefix))) return false
      return !EXCLUDE_SUFFIXES.some((suffix) => rel.endsWith(suffix))
    })
    .sort()
    .map((file) => {
      const rel = relative(PACKAGE_DIR, file).split(sep).join("/")
      // Files outside the package dir (repo-root LICENSE) flatten to basename.
      const memberName = rel.startsWith("..") ? file.split(sep).pop() : rel
      return { name: `package/${memberName}`, content: readFileSync(file, "utf8") }
    })
  if (files.length === 0) throw new Error("no package files collected")
  return files
}

export function buildEmbedded() {
  const pkgPath = join(PACKAGE_DIR, "package.json")
  const raw = readFileSync(pkgPath, "utf8")
  const pkg = JSON.parse(raw) as Record<string, unknown>
  const publishedAt = statSync(pkgPath).mtime.toISOString()

  const manifest: Record<string, unknown> = { ...pkg }
  delete manifest.devDependencies
  delete manifest.scripts

  const files = collectPackageFiles()
  const tarball = createTarGz(files)
  const unpackedSize = files.reduce(
    (sum, file) => sum + Buffer.byteLength(file.content, "utf8"),
    0,
  )

  return {
    version: String(pkg.version),
    description: String(pkg.description ?? ""),
    publishedAt,
    readme: readFileSync(join(PACKAGE_DIR, "README.md"), "utf8"),
    manifest,
    tarballBase64: tarball.toString("base64"),
    shasum: createHash("sha1").update(tarball).digest("hex"),
    integrity: `sha512-${createHash("sha512").update(tarball).digest("base64")}`,
    fileCount: files.length,
    unpackedSize,
  }
}

function main(): void {
  const embedded = buildEmbedded()
  mkdirSync(join(REGISTRY_DIR, "src", "generated"), { recursive: true })
  const body = JSON.stringify(embedded, null, 2)
  const ts = `// @generated by src/build/embed-package.ts. Do not edit.
// Embeds the real cfnext@${embedded.version} package for the registry Worker.
export const EMBEDDED = ${body} as const
`
  writeFileSync(OUT_FILE, ts)
  const kb = Math.round((embedded.tarballBase64.length * 3) / 4 / 1024)
  console.log(`embedded cfnext@${embedded.version}: ${embedded.fileCount} files, ${kb}KB tarball → ${relative(process.cwd(), OUT_FILE)}`)
}

main()
